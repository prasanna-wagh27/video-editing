#!/usr/bin/env python3
"""timing.mjs from captions.js (WORD_T) + script_hi.txt + VO pauses:
LT[i] = start of script line i, WT[i] = [[word, start], ...], CUT[i] = scene-cut time before line i (middle of the VO pause before it),
END = end of the last spoken word. Run from outgrid-reels/: python3 reels/business-process-audit/make_timing.py reels/business-process-audit"""
import json, re, subprocess
import sys
D = sys.argv[1].rstrip('/')
cap = open(f'{D}/captions.js').read()
WT = json.loads(re.search(r'WORD_T = (\[.*?\]);', cap).group(1))
lines = [l.split() for l in open(f'{D}/script_hi.txt').read().strip().split('\n')]
assert sum(map(len, lines)) == len(WT), (sum(map(len, lines)), len(WT))
out = subprocess.run(['scripts/vo_pauses.sh', f'{D}/public/vo.mp3'], capture_output=True, text=True).stdout
segs = [tuple(map(float, m)) for m in re.findall(r'\[([\d.]+), ([\d.]+)\]', out)]
k = 0; LT = []; W = []
for ln in lines:
    W.append([[w.replace('*', ''), round(WT[k + j], 3)] for j, w in enumerate(ln)]); LT.append(round(WT[k], 3)); k += len(ln)
CUT = []
for t in LT:
    prev = [b for a, b in segs if b <= t + 0.08]            # speech segments that end before this line starts
    nxt = [a for a, b in segs if a >= (prev[-1] if prev else 0)]
    if prev and nxt and t - prev[-1] < 1.6:
        CUT.append(round((prev[-1] + max(nxt[0], prev[-1])) / 2 if nxt[0] > prev[-1] else prev[-1], 3))
        CUT[-1] = round(min(CUT[-1], t - 0.04), 3)
    else:
        CUT.append(round(t - 0.25, 3))
END = segs[-1][1]
open(f'{D}/timing.mjs', 'w').write('// generated by make_timing.py\n' + f'export const LT = {json.dumps(LT)};\nexport const CUT = {json.dumps(CUT)};\nexport const END = {END};\n'
                                   + 'export const WT = ' + json.dumps(W, ensure_ascii=False) + ';\n')
print(len(LT), 'lines, END', END)
